import FoundationModels

public struct ModelStopData: Sendable {

    public let stopReason: ModelStopReason

    public let invocationState: InvocationState

    public let usage: LanguageModelSession.Usage

    public var rawContent: GeneratedContent? {
        switch stopReason {
        case .endTurn(let response):
            return response.segments.rawGeneratedContent
        case .toolUse(let toolCalls):
            return GeneratedContent(kind: .array(toolCalls.map(\.arguments)))
        default: return nil
        }
    }

    init(
        stopReason: ModelStopReason,
        invocationState: InvocationState,
        usage: LanguageModelSession.Usage
    ) {
        self.stopReason = stopReason
        self.invocationState = invocationState
        self.usage = usage
    }

    init(
        response: Transcript.Response,
        invocationState: InvocationState,
        usage: LanguageModelSession.Usage
    ) {
        self.stopReason = .endTurn(response)
        self.invocationState = invocationState
        self.usage = usage
    }

    init(
        toolCalls: Transcript.ToolCalls,
        invocationState: InvocationState,
        usage: LanguageModelSession.Usage
    ) {
        self.stopReason = .toolUse(toolCalls)
        self.invocationState = invocationState
        self.usage = usage
    }

    init(
        error: Error,
        invocationState: InvocationState,
        usage: LanguageModelSession.Usage
    ) {
        self.stopReason = ModelStopReason.fromError(error)
        self.invocationState = invocationState
        self.usage = usage
    }

}

extension ModelStopData: CustomStringConvertible {
    public var description: String {
        return stopReason.description
    }
}

public enum ModelStopReason: Sendable {
    case endTurn(Transcript.Response)

    case toolUse(Transcript.ToolCalls)

    case generalFailure(Error)

    // MARK: - LanguageModel Error Mapping
    /// The session's transcript exceeded the model's context size.
    ///
    /// You can recover from this error by removing entries from the transcript and trying again.
    ///
    /// For more information on managing the context window size, see <doc:managing-the-context-window>.
    case contextSizeExceeded(LanguageModelError.ContextSizeExceeded)

    /// The session has been rate limited.
    ///
    /// This failure can happen if you make too many requests in a short window.
    /// You can recover from this error by spacing your requests or reducing system load. The
    /// exact solution may be model dependent.
    case rateLimited(LanguageModelError.RateLimited)

    /// The model's safety guardrails were triggered by content in a
    /// prompt or the response generated by the model.
    case guardrailViolation(LanguageModelError.GuardrailViolation)

    /// The model refused to answer.
    ///
    /// This failure can happen for prompts that do not violate any guardrail policy, but
    /// the model isn't able to provide the kind of response you requested. You can
    /// choose to handle this by showing a predetermined message of your choice.
    case refusal(LanguageModelError.Refusal)

    /// The model being used doesn't support a particular feature.
    ///
    /// This failure can happen if you use capabilities like guided generation or tool calling
    /// with a model that does not support them.
    case unsupportedCapability(LanguageModelError.UnsupportedCapability)

    /// The prompt contains content that the model cannot process.
    ///
    /// This failure occurs when you include unsupported file types, corrupted data, or custom
    /// content formats that the model doesn't recognize.
    case unsupportedTranscriptContent(
        LanguageModelError.UnsupportedTranscriptContent
    )

    /// An unsupported generation guide was used.
    ///
    /// This failure occurs if you attempt to use generation guides that a model does not support.
    /// For example, many models don't support certain guides using certain regex patterns.
    case unsupportedGenerationGuide(
        LanguageModelError.UnsupportedGenerationGuide
    )

    /// The model was prompted to respond in a language that it does not support.
    case unsupportedLanguageOrLocale(
        LanguageModelError.UnsupportedLanguageOrLocale
    )

    /// The request timed out before the model could produce a response.
    case timeout(LanguageModelError.Timeout)

    // MARK: - LanguageModelSession.Error Mapping
    /// The session received multiple concurrent requests.
    ///
    /// A language model session only supports one request at a time.
    /// Wait for the current request to complete before starting another.
    case concurrentRequests

    /// A request mutated the session's transcript while it was in progress.
    ///
    /// Do not modify the transcript while a request is being processed.
    case transcriptMutationWhileResponding

    static func fromError(_ error: Error) -> Self {
        if let error = error as? LanguageModelError {
            switch error {
            case .contextSizeExceeded(let contextSizeExceeded):
                return .contextSizeExceeded(contextSizeExceeded)
            case .rateLimited(let rateLimited):
                return .rateLimited(rateLimited)
            case .guardrailViolation(let guardrailViolation):
                return .guardrailViolation(guardrailViolation)
            case .refusal(let refusal):
                return .refusal(refusal)
            case .unsupportedCapability(let unsupportedCapability):
                return .unsupportedCapability(unsupportedCapability)
            case .unsupportedTranscriptContent(let unsupportedTranscriptContent):
                return .unsupportedTranscriptContent(
                    unsupportedTranscriptContent
                )
            case .unsupportedGenerationGuide(let unsupportedGenerationGuide):
                return .unsupportedGenerationGuide(unsupportedGenerationGuide)
            case .unsupportedLanguageOrLocale(let unsupportedLanguageOrLocale):
                return .unsupportedLanguageOrLocale(unsupportedLanguageOrLocale)
            case .timeout(let timeout):
                return .timeout(timeout)
            @unknown default:
                return .generalFailure(error)
            }
        }

        if let error = error as? LanguageModelSession.Error {
            switch error {

            case .concurrentRequests:
                return .concurrentRequests
            case .transcriptMutationWhileResponding:
                return .transcriptMutationWhileResponding
            @unknown default:
                return .generalFailure(error)
            }
        }

        return .generalFailure(error)
    }
}

extension ModelStopReason: CustomStringConvertible {
    public var description: String {
        let languageModelError = "LanguageModelError: "
        let sessionError = "LanguageModelSession Error: "
        switch self {
        case .endTurn(let response):
            return response.description
        case .toolUse(let toolCall):
            return toolCall.description
        case .generalFailure(let error):
            return "Error: " + error.localizedDescription
        case .contextSizeExceeded(let error):
            return languageModelError + error.debugDescription
        case .rateLimited(let error):
            return languageModelError + error.debugDescription
        case .guardrailViolation(let error):
            return languageModelError + error.debugDescription
        case .refusal(let error):
            return languageModelError + error.debugDescription
        case .unsupportedCapability(let error):
            return languageModelError + error.debugDescription
        case .unsupportedTranscriptContent(let error):
            return languageModelError + error.debugDescription
        case .unsupportedGenerationGuide(let error):
            return languageModelError + error.debugDescription
        case .unsupportedLanguageOrLocale(let error):
            return languageModelError + error.debugDescription
        case .timeout(let error):
            return languageModelError + error.debugDescription
        case .concurrentRequests:
            return sessionError
                + "The session received multiple concurrent requests. A language model session only supports one request at a time. Wait for the current request to complete before starting another."
        case .transcriptMutationWhileResponding:
            return sessionError
                + "A request mutated the session’s transcript while it was in progress. Do not modify the transcript while a request is being processed."
        }
    }
}
